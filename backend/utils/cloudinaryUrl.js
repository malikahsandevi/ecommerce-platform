// Cloudinary asset protection — one helper for the whole backend.
//
// Delivery model: every asset this API stores is an AUTHENTICATED-type
// asset on Cloudinary. The URL kept in the database is the canonical
// UNSIGNED authenticated URL — opened directly (pasted into a browser,
// hotlinked from another site) it answers 401. The API never serves
// that stored string to the admin: responses pass through signForResponse
// below, which rewrites every stored Cloudinary URL into a SIGNED
// delivery URL (cloudinary.url with sign_url) that loads normally.
// Anything the client sends back is canonicalised again on the way in
// (canonicaliseDeep), so signed URLs never leak into stored records.
//
// Expiry note: the installed SDK (cloudinary@2.7) ignores `expires_at`
// for delivery URLs (it is only honoured by private_download_url), so
// signed URLs carry no expiry — protection rests on the signature
// itself: unsigned or tampered links fail with 401.
const cloudinary = require('../config/cloudinary');
const { currentCredentials } = require('./credentials');

// The cloud name comes from the credentials store (Settings →
// Credentials; environment is the seed/fallback). It is read through
// the resolver's snapshot on every call, so a cloud name changed in
// the panel takes effect here without a restart — the snapshot is
// refreshed per request by the app-level middleware.
const cloudName = () => currentCredentials().cloudinaryCloudName || '';
const RESOURCE_TYPES = ['image', 'video', 'raw'];
const DELIVERY_TYPES = ['upload', 'authenticated', 'private'];

// Matches every Cloudinary delivery URL of THIS cloud, in any form we
// can meet: upload/authenticated/private, with or without a signature
// segment, with or without a version segment. Built lazily and cached
// per cloud name (the name can change at runtime now).
let patternCache = { name: null, pattern: null };
const urlPattern = () => {
    const name = cloudName();
    if (patternCache.name !== name) {
        patternCache = {
            name,
            pattern: name
                ? new RegExp(
                      `^https://res\\.cloudinary\\.com/${name}/(image|video|raw)/(upload|authenticated|private)/(?:s--[^/]+--/)?(?:v\\d+/)?(.+)$`,
                  )
                : null,
        };
    }
    return patternCache.pattern;
};

/**
 * Parse one of this cloud's delivery URLs into its parts.
 * Returns { resourceType, deliveryType, publicId, format } or null for
 * anything that is not this cloud's URL (external images stay untouched).
 * For `raw` assets the extension belongs to the public_id itself.
 */
function parseCloudinaryUrl(value) {
    const pattern = urlPattern();
    if (typeof value !== 'string' || !pattern) return null;
    // Signed URLs generated by the SDK carry a `?_a=…` analytics query —
    // it is not part of the asset's identity and must never be stored.
    const clean = value.split(/[?#]/)[0];
    const match = clean.match(pattern);
    if (!match) return null;
    const [, resourceType, deliveryType, tail] = match;
    if (resourceType === 'raw') {
        return { resourceType, deliveryType, publicId: tail, format: '' };
    }
    const dot = tail.lastIndexOf('.');
    if (dot <= 0) {
        return { resourceType, deliveryType, publicId: tail, format: '' };
    }
    return {
        resourceType,
        deliveryType,
        publicId: tail.slice(0, dot),
        format: tail.slice(dot + 1),
    };
}

/** The canonical STORED form: authenticated type, no signature, no version. */
function canonicalUrl({ resourceType, publicId, format }) {
    const suffix = format ? `.${format}` : '';
    return `https://res.cloudinary.com/${cloudName()}/${resourceType}/authenticated/${publicId}${suffix}`;
}

/** A signed delivery URL for one stored URL (or an already-signed one). */
function signedUrl(value) {
    const parts = parseCloudinaryUrl(value);
    if (!parts) return value;
    return cloudinary.url(parts.publicId, {
        resource_type: parts.resourceType,
        type: 'authenticated',
        sign_url: true,
        secure: true,
        ...(parts.format ? { format: parts.format } : {}),
    });
}

const isPlainObject = (v) =>
    v !== null && typeof v === 'object' && !Array.isArray(v) && !(v instanceof Date);

/** Deep-walk a JSON-shaped value, mapping every string through fn. */
function mapStrings(value, fn, depth = 0) {
    if (depth > 12 || value === null || value === undefined) return value;
    if (typeof value === 'string') return fn(value);
    if (Array.isArray(value)) return value.map((item) => mapStrings(item, fn, depth + 1));
    if (isPlainObject(value)) {
        const out = {};
        for (const [key, val] of Object.entries(value)) {
            out[key] = mapStrings(val, fn, depth + 1);
        }
        return out;
    }
    return value;
}

/** Response direction: stored URL → signed delivery URL. */
function signDeep(value) {
    return mapStrings(value, (s) => signedUrl(s));
}

/** Request direction: any form of our URL → canonical stored form. */
function canonicaliseDeep(value) {
    return mapStrings(value, (s) => {
        const parts = parseCloudinaryUrl(s);
        return parts ? canonicalUrl(parts) : s;
    });
}

/**
 * Express middleware: sign every Cloudinary URL in JSON responses.
 * Handlers can opt out per-response with res.locals.skipUrlSigning
 * (the protection-migration endpoint reports raw stored values).
 */
function responseSigner(req, res, next) {
    const originalJson = res.json.bind(res);
    res.json = (body) => {
        if (res.locals.skipUrlSigning || body === null || typeof body !== 'object') {
            return originalJson(body);
        }
        // Normalise through a JSON round-trip first: handlers hand
        // res.json Mongoose documents whose toJSON must run before the
        // value can be walked as plain data.
        const plain = JSON.parse(JSON.stringify(body));
        return originalJson(signDeep(plain));
    };
    next();
}

/** Express middleware: canonicalise Cloudinary URLs in request bodies. */
function requestCanonicaliser(req, res, next) {
    if (req.body && typeof req.body === 'object') {
        req.body = canonicaliseDeep(req.body);
    }
    next();
}

/**
 * Make sure an asset exists as an authenticated-type copy and the old
 * public (upload-type) copy is gone. Idempotent: when the authenticated
 * copy already exists only the public copy is (re-)checked for removal.
 * Returns the authenticated asset's facts as the Admin API reports them.
 */
async function ensureAuthenticatedAsset({ publicId, resourceType, sourceUrl }) {
    let authed = null;
    try {
        authed = await cloudinary.api.resource(publicId, {
            resource_type: resourceType,
            type: 'authenticated',
        });
    } catch {
        authed = null;
    }
    if (!authed) {
        if (!sourceUrl) {
            throw new Error(`No source URL to migrate asset ${publicId}`);
        }
        authed = await cloudinary.uploader.upload(sourceUrl, {
            public_id: publicId,
            resource_type: resourceType,
            type: 'authenticated',
        });
    }
    // Remove the public copy (with CDN invalidation) so the old public
    // link dies. Best effort: a 'not found' simply means it is gone.
    try {
        await cloudinary.uploader.destroy(publicId, {
            resource_type: resourceType,
            type: 'upload',
            invalidate: true,
        });
    } catch {
        /* the authenticated copy is already authoritative */
    }
    return authed;
}

/** Destroy an asset in whichever delivery type it exists (best effort). */
async function destroyAsset(publicId, resourceType) {
    for (const type of ['authenticated', 'upload']) {
        try {
            const result = await cloudinary.uploader.destroy(publicId, {
                resource_type: resourceType,
                type,
                invalidate: true,
            });
            if (result && result.result === 'ok') return result;
        } catch {
            /* try the other type */
        }
    }
    return { result: 'not found' };
}

module.exports = {
    parseCloudinaryUrl,
    canonicalUrl,
    signedUrl,
    signDeep,
    canonicaliseDeep,
    responseSigner,
    requestCanonicaliser,
    ensureAuthenticatedAsset,
    destroyAsset,
    RESOURCE_TYPES,
    DELIVERY_TYPES,
};
